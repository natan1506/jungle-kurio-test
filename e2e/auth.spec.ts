import { addToCart, expect, gotoApp, login, test, USERS } from './fixtures'

test.describe('Conta e sessão', () => {
  test('cadastro com validação e conflito de e-mail @main', async ({ page }) => {
    await page.goto('/cadastro')
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('button', { name: 'Criar perfil' }).click()
    await expect(dialog.getByText('Informe um e-mail válido.')).toBeVisible()
    await expect(dialog.getByLabel('E-mail', { exact: true })).toHaveAttribute('aria-invalid', 'true')

    await dialog.getByLabel('Nome de usuário').fill('novo.colecionador')
    await dialog.getByLabel('E-mail', { exact: true }).fill(USERS.ana.email)
    await dialog.getByLabel('Senha', { exact: true }).fill('Senha1234')
    await dialog.getByLabel('Confirmar senha').fill('Senha1234')
    await dialog.getByRole('button', { name: 'Criar perfil' }).click()
    await expect(dialog.getByText('Este e-mail já está cadastrado.')).toBeVisible()

    await dialog.getByLabel('E-mail', { exact: true }).fill('novo@kurio.dev')
    await dialog.getByRole('button', { name: 'Criar perfil' }).click()
    await expect(page.getByRole('dialog')).toBeHidden()
    await expect(page).not.toHaveURL(/\/cadastro/)
    await page.goto('/conta/perfil')
    await expect(page.getByLabel(/^E-mail/)).toHaveValue('novo@kurio.dev')
  })

  test('login inválido, sucesso, sessão após refresh e logout', async ({ page }) => {
    await page.goto('/entrar')
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('E-mail', { exact: true }).fill(USERS.ana.email)
    await dialog.getByLabel('Senha', { exact: true }).fill('errada123')
    await dialog.getByRole('button', { name: 'Entrar', exact: true }).click()
    await expect(dialog.getByText('E-mail ou senha incorretos.')).toBeVisible()

    await login(page, 'ana')
    await page.reload()
    await expect(page.getByRole('button', { name: 'Menu da conta de Ana Souza' })).toBeVisible()

    await page.goto('/conta/perfil')
    await page.getByRole('navigation', { name: 'Conta' }).getByRole('button', { name: 'Sair' }).click()
    await expect(page).toHaveURL(/\/entrar/)
    await page.goto('/conta/perfil')
    await expect(page).toHaveURL(/\/entrar\?redirect=%2Fconta%2Fperfil/)
  })

  test('rota privada redireciona ao login e retorna ao fluxo anterior', async ({ page }) => {
    await page.goto('/conta/carteiras')
    await expect(page).toHaveURL(/\/entrar/)
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('E-mail', { exact: true }).fill(USERS.ana.email)
    await dialog.getByLabel('Senha', { exact: true }).fill(USERS.ana.password)
    await dialog.getByRole('button', { name: 'Entrar', exact: true }).click()
    await expect(page).toHaveURL(/\/conta\/carteiras/)
    await expect(page.getByRole('heading', { name: 'Carteira principal' })).toBeVisible()
  })

  test('expiração de sessão durante a navegação preserva o destino', async ({ page, mock }) => {
    await login(page, 'ana')
    await page.goto('/conta/perfil')
    await expect(page.getByLabel('Nome de exibição')).toHaveValue('Ana Souza')
    await mock.expireSessions()
    await page.getByLabel('Nome de exibição').fill('Ana S.')
    await page.getByRole('button', { name: 'Salvar' }).click()
    await expect(page).toHaveURL(/\/entrar\?.*reason=expired/)
    await expect(page.getByRole('dialog').getByText('Sua sessão expirou')).toBeVisible()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('E-mail', { exact: true }).fill(USERS.ana.email)
    await dialog.getByLabel('Senha', { exact: true }).fill(USERS.ana.password)
    await dialog.getByRole('button', { name: 'Entrar', exact: true }).click()
    await expect(page).toHaveURL(/\/conta\/perfil/)
  })

  test('troca de usuário não expõe dados privados do anterior', async ({ page }) => {
    await login(page, 'ana')
    await addToCart(page, 'emerald-ape-042')
    await page.goto('/carrinho')
    await expect(page.getByTestId('cart-item')).toHaveCount(1)
    await page.goto('/conta/perfil')
    await page.getByRole('navigation', { name: 'Conta' }).getByRole('button', { name: 'Sair' }).click()
    await expect(page).toHaveURL(/\/entrar/)
    await login(page, 'bruno')
    await page.goto('/carrinho')
    await expect(page.getByText('Seu carrinho está vazio.')).toBeVisible()
    await gotoApp(page, '/conta/carteiras')
    await expect(page).toHaveURL(/\/conta\/carteiras/)
    await expect(page.getByRole('heading', { name: 'Carteira principal' })).toBeVisible()
    await expect(page.getByLabel(/^Endereço da carteira/).first()).toHaveValue('')
    await gotoApp(page, '/?favorites=true')
    await expect(page.getByText('Nenhum NFT encontrado')).toBeVisible()
  })
})
